package Com.loops;

public class Loops {

	public static void main(String[] args) {
		int i;
		for(i=0;i<=10;i++)
		{
			System.out.println(i);		}
	
	
	int x = 10;
	while(x<20) {
		System.out.println(x);
		x++;
	}
	
	//do while
	int y=1;
	do {
		System.out.println("the y value is"+y);
		y++;
	}while(y<=100);

}
}